export async function loadBundledRoute(key: string) {
  const course = bundledRoutes.find((entry) => entry.key === key);
  if (!course) throw new Error("Unknown course.");
  const response = await fetch(`/routes/${course.slug}.json`);
  if (!response.ok)
    throw new Error(
      "Could not load the selected route. Try selecting it again.",
    );
  const { buildRoute } = await import("./package");
  return buildRoute(await response.json());
}
